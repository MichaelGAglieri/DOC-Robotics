"""Deriva DocArm5.proto dal PROTO UR3e R2025a, conservando mesh e primi 5 assi."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'architetture/laboratorio/ros2_ws/src/doc_lab'))
from doc_lab.doc5_kinematics import TOOLSLOT


def source():
    original = (ROOT/'webots_sim/protos/vendor/UR3e_R2025a.proto').read_text()
    motor = original.index('name "wrist_3_joint"')
    start = original.rfind('HingeJoint {', 0, motor)
    depth = 0
    for end in range(original.index('{', start), len(original)):
        depth += (original[end] == '{')-(original[end] == '}')
        if depth == 0:
            break
    mount = 'Pose {\n                                      translation '+ ' '.join(str(v) for v in TOOLSLOT) + '\n                                      children IS toolSlot\n                                    }'
    result = original[:start]+mount+original[end+1:]
    result = result.replace('PROTO UR3e [', 'PROTO DocArm5 [')
    result = result.replace('name            "UR3e"', 'name            "DOC 5 assi"')
    result = result.replace('model "UR3e"', 'model "DOC 5 assi (geometria UR3e)"')
    prefix = 'vendor/webots/projects/robots/universal_robots/protos/'
    result = re.sub(r'"(UR3e/[^\"]+)"', lambda m: '"'+prefix+m.group(1)+'"', result)
    result = result.replace('webots://projects/appearances/protos/',
        'vendor/webots/projects/appearances/protos/')
    result = result.replace('# An Universal Robots UR3e robotic arm.',
        '# Derived from the Apache-2.0 UR3e R2025a model: wrist_3_joint and wrist_3_link removed.\n'
        '# Gripper attached directly to wrist_2_link. Generated by scripts/genera_doc5.py.')
    # Palette DOC: solo colori; mesh, giunti e parametri fisici originali.
    result = result.replace('baseColor 0.6 0.6 0.6', 'baseColor 0.40 0.88 0.012')
    result = result.replace('baseColor 0 0 0', 'baseColor 0.018 0.022 0.018')
    result = result.replace('baseColor 0.490196 0.678431 0.8', 'baseColor 0.018 0.022 0.018')
    result = result.replace('DEF METAL_APPEARANCE_LIGHT PBRAppearance {',
        'DEF METAL_APPEARANCE_LIGHT PBRAppearance {\n                      baseColor 0.40 0.88 0.012')
    # Base lime separata: le altre parti di METAL_APPEARANCE sono corpi dei giunti.
    result = result.replace('appearance DEF METAL_APPEARANCE PBRAppearance {',
        'appearance PBRAppearance {', 1)
    result = result.replace('appearance USE METAL_APPEARANCE',
        'appearance DEF METAL_APPEARANCE PBRAppearance { baseColor 0.018 0.022 0.018 roughness 0.7 }', 1)
    # Preserve the current per-mesh palette rather than changing shared materials.
    colors = {'upper_arm_link_3.obj': '0.018 0.022 0.018',
              'upper_arm_link_8.obj': '0.018 0.022 0.018',
              'forearm_link_2.obj': '0.40 0.88 0.012',
              'forearm_link_3.obj': '0.40 0.88 0.012'}
    for mesh, color in colors.items():
        pattern = (r'appearance USE \w+(?=\s+geometry Mesh \{\s+url "[^"\n]*/'
                   + re.escape(mesh) + r'")')
        result, count = re.subn(pattern, 'appearance PBRAppearance { baseColor '
                               + color + ' roughness 0.7 metalness 0 }', result)
        assert count == 1, mesh
    assert result.count('HingeJoint {') == 5
    assert 'wrist_3' not in result.replace('wrist_3_joint and wrist_3_link removed.', '')
    return result


def generate():
    destination = ROOT/'webots_sim/protos/DocArm5.proto'
    destination.write_text(source())
    return destination


if __name__ == '__main__':
    print(generate())
